/*
 * check-mtr-fare.js — MTR Bus 詳請 must show a fare for EVERY route
 * =================================================================
 * The bug this guards against is a silent one. index.html used to read MTR fares
 * from routeFareList.min.json under the company key `lrtfeeder`. That file has
 * 60 lrtfeeder (route, serviceType, direction) entries but `fares: null` on 15
 * of them — and the 15 were the popular ones (all four 大埔 routes, plus
 * secondary serviceTypes of K51/K52/K66/K68). The 詳請 panel simply rendered no
 * fare row, and the sidebar fare line stayed blank. Nothing errored, so nothing
 * looked broken.
 *
 * Fares now come from the official data.gov.hk CSV (mtr-fares.min.json,
 * generated by tools/build-mtr-fares.js). This probe drives the real page for
 * one route from EACH previously-missing group and asserts a non-zero fare is
 * visible, so a regression to the old source is caught immediately.
 *
 * Usage: node tools/check-mtr-fare.js [--url http://127.0.0.1:8000] [--shot <dir>]
 */
const { chromium } = require('./pw');
const fs = require('fs');

const argUrl = (() => {
  const i = process.argv.indexOf('--url');
  return i !== -1 ? process.argv[i + 1] : 'http://127.0.0.1:8000';
})();
const shotIdx = process.argv.indexOf('--shot');
const shotDir = shotIdx !== -1 ? process.argv[shotIdx + 1] : null;
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';

/* Every route that had NO fare in routeFareList.min.json. Each one must now
   show a fare. Expected values come from the official CSV, so this also acts as
   a correctness check, not merely a presence check. */
const CASES = [
  { route: 'K12', expect: 4.8 },   // 大埔 group — fares were null
  { route: 'K14', expect: 4.8 },
  { route: 'K18', expect: 4.8 },
  { route: 'K51', expect: 5.1 },   // K51 s3 was null; s1 had fares
  { route: 'K52', expect: 5.1 },   // K52 s2 was null
  { route: 'K66', expect: 5.1 },   // K66 s2 was null
  { route: 'K68', expect: 5.1 },   // K68 s3 was null
  { route: 'K52A', expect: 10.1 }, // control: this one always had a fare
];

async function run(browser, { route, expect }) {
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push('pageerror: ' + String(e)));
  p.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text()); });

  await p.goto(`${argUrl}/index.html`, { waitUntil: 'load' });
  await p.waitForTimeout(3000);

  /* Equip the company to MTR and search. Doing it through the real controls
     (rather than poking state) means a broken company row is also caught. */
  await p.evaluate(() => {
    const b = [...document.querySelectorAll('.company-btn')].find(x => (x.textContent || '').includes('港鐵巴士'));
    if (b) b.click();
  });
  await p.waitForTimeout(2000);

  await p.evaluate((r) => {
    const inp = document.querySelector('.row input');
    inp.focus();
    const setter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set;
    setter.call(inp, r);
    inp.dispatchEvent(new Event('input', { bubbles: true }));
    const btn = [...document.querySelectorAll('button')].find(b => (b.textContent || '').trim() === '查詢');
    if (btn) btn.click();
  }, route);
  await p.waitForTimeout(6000);

  /* A direction picker blocks everything until a choice is made. */
  const dirs = await p.evaluate(() =>
    [...document.querySelectorAll('.direction-picker li')].map(n => n.textContent.trim()));
  if (dirs.length) {
    await p.evaluate(() => { const li = document.querySelectorAll('.direction-picker li'); if (li[0]) li[0].click(); });
    await p.waitForTimeout(6000);
  }

  /* The sidebar fare line (`.fare-line`) is gated on a stop being selected —
     `computeBoardingFare` needs a stop to know how far you are boarding. With
     no stop chosen the line is legitimately absent, so the probe must click a
     stop before asserting on it. Without this click the probe reported FAIL on
     a working page (the fare IS correct once a stop is picked).
     ⚠️ Some routes legitimately have no stop list to click: K14's live API
     currently returns `busStop: []` (an upstream gap — K12/K17/K18 all return
     stops). For those the sidebar assertion is skipped and only the 詳請 fare is
     checked, so an upstream outage does not masquerade as a hard-coded failure. */
  const stopCount = await p.evaluate(() => document.querySelectorAll('.stop-list li').length);
  if (stopCount) {
    await p.evaluate(() => { const li = document.querySelector('.stop-list li'); if (li) li.click(); });
    await p.waitForTimeout(4000);
  }

  /* Sidebar fare line (only rendered once a stop is selected). */
  const sidebar = await p.evaluate(() => {
    const el = document.querySelector('.fare-line');
    return el ? el.textContent.replace(/\s+/g, ' ').trim() : '';
  });

  /* 詳請 panel fare rows. */
  let detail = { open: false, text: '', rows: [] };
  const hasDetail = await p.evaluate(() => !!document.querySelector('.detail-btn'));
  if (hasDetail) {
    await p.evaluate(() => document.querySelector('.detail-btn')?.click());
    await p.waitForTimeout(3000);
    detail = await p.evaluate(() => {
      const m = document.querySelector('.detail-modal');
      if (!m) return { open: false, text: '', rows: [] };
      const rows = [...m.querySelectorAll('.fare-row, .detail-fare-row, tr')]
        .map(n => n.textContent.replace(/\s+/g, ' ').trim()).filter(Boolean);
      return { open: true, text: (m.textContent || '').replace(/\s+/g, ' '), rows };
    });
    if (shotDir) await p.screenshot({ path: `${shotDir}/mtr-fare-${route}-detail.png` });
  }

  if (shotDir) await p.screenshot({ path: `${shotDir}/mtr-fare-${route}.png` });
  await ctx.close();

  /* A fare is "present" only if a $ amount at least the expected value shows up.
     Matching the exact expected value catches "shows a stale/other route's fare"
     as well as "shows nothing". */
  const money = (t) => {
    const m = (String(t).match(/\$\s*([0-9]+(?:\.[0-9]+)?)/g) || [])
      .map(s => parseFloat(s.replace(/[^0-9.]/g, '')));
    return m;
  };
  const sideVals = money(sidebar);
  const detailVals = money(detail.text);

  return {
    route, expect, dirs, sidebar, detailOpen: detail.open, detailRows: detail.rows,
    sideVals, detailVals, errs, stopCount,
  };
}

(async () => {
  const browser = await chromium.launch({ executablePath: CHROME, headless: true });
  if (shotDir && !fs.existsSync(shotDir)) fs.mkdirSync(shotDir, { recursive: true });

  let failed = false;
  for (const c of CASES) {
    const r = await run(browser, c);
    const near = (arr) => arr.some(v => Math.abs(v - c.expect) < 0.05);
    /* The sidebar line can only be asserted when the page actually has a stop
       list; K14 currently returns none from the upstream API. */
    const sideOk = r.stopCount === 0 || near(r.sideVals);
    const detailOk = !r.detailOpen || near(r.detailVals);
    const ok = sideOk && detailOk && r.errs.length === 0;

    console.log(`\n### ${c.route}  (官方票價 $${c.expect.toFixed(1)})`);
    console.log(`  directions: ${r.dirs.join(' / ') || '(none)'}   stops: ${r.stopCount}`);
    console.log(`  sidebar fare line: ${r.sidebar || '(EMPTY)'}   -> ${r.stopCount === 0 ? 'SKIPPED (no stops from API)' : (sideOk ? 'OK' : 'MISSING/WRONG')}`);
    console.log(`  detail open=${r.detailOpen} rows=${r.detailRows.length}`);
    if (r.detailOpen) console.log(`    rows: ${r.detailRows.slice(0, 4).join(' | ')}   -> ${detailOk ? 'OK' : 'MISSING/WRONG'}`);
    if (r.errs.length) r.errs.slice(0, 3).forEach(e => console.log('    ', e));
    console.log(`  => ${ok ? 'PASS' : 'FAIL'}`);
    if (!ok) failed = true;
  }

  await browser.close();
  console.log(failed ? '\nRESULT: FAIL' : '\nRESULT: ALL PASS');
  process.exit(failed ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
